# 以 # 开头的行叫「注释」，电脑会完全忽略它。
# 注释是写给人看的，用来解释下面这行代码在干什么。
# 你以后写代码，注释要写给自己看——三个月后你会感谢自己。


# ---------- 1. print：把东西显示到屏幕上 ----------
# 括号里的东西会被打印出来。文字要用引号包住。
print("你好，我是 Python")

# print 可以一次接收多个东西，用逗号隔开，
# 它们会被一个空格自动连起来。
print("1 + 1 =", 1 + 1)

# 注意上面这个例子：1 + 1 没有引号，所以电脑会先算出结果 2，再打印。
# 而 "1 + 1" 有引号，就是一段文字，原样输出。
print("1 + 1")


# ---------- 2. 变量：给数据贴个标签 ----------
# = 不是数学里的「等于」，而是「把右边的东西，存到左边的名字里」。
# 想象你有一个盒子，你在盒子上写了一个名字，然后把东西放进去。
name = "陈同学"
age = 18
height = 1.75

print(name)
print("年龄：", age)
print("身高：", height)

# 变量可以重新赋值，新的值会覆盖旧的
age = 19
print("过了一年，年龄变成：", age)

# 变量名要有意义。你想一下：下面两个哪个三个月后还看得懂？
#   a = 1.75        （看不懂 a 是什么）
#   height = 1.75   （一眼就知道是身高）


# ---------- 3. 类型：数据是分种类的 ----------
# Python 会自动判断类型，你不用声明。但你要知道有哪几种。
#
#   int    整数        18
#   float  小数        1.75
#   str    字符串      "你好"（文字，必须有引号）
#   bool   布尔值      True / False（只有两种，注意首字母大写）
#
# type() 这个函数会告诉你某个东西是什么类型。
print(type(18))       # <class 'int'>
print(type(1.75))     # <class 'float'>
print(type("你好"))    # <class 'str'>
print(type(True))     # <class 'bool'>


# ---------- 4. 把变量塞进一句话里 ----------
# 拼接字符串用 + ，但 + 只能连接两个字符串，不能直接连数字。
first = "环境"
second = "工程"
print(first + second)

# 推荐用 f-string：字符串前面加个 f，{} 里可以直接写变量名。
major = "环境工程"
goal = "计算机科学"
print(f"我现在的专业是{major}，我想转去{goal}。")
print(f"我今年{age}岁。")


# ---------- 5. 算术运算 ----------
print("加法  7 + 3  =", 7 + 3)
print("减法  7 - 3  =", 7 - 3)
print("乘法  7 * 3  =", 7 * 3)
print("除法  7 / 3  =", 7 / 3)    # 结果永远是小数
print("整除  7 // 3 =", 7 // 3)   # 只保留商的整数部分
print("取余  7 % 3  =", 7 % 3)    # 只保留余数
print("乘方  7 ** 2 =", 7 ** 2)

# // 和 % 这两个，你以后写程序会天天用到。
# 比如判断一个数是奇数还是偶数：n % 2 == 0 就是偶数。
# 比如把 137 秒换算成「2 分 17 秒」：137 // 60 和 137 % 60。
